//! `partition`::part — the verbatim
//! items of the round-7 file-split pass (the parent glob
//! re-exports preserve every pre-split path).
use super::*;
use crate::manifest::Entry;
use crate::{ClassPlan, Options, Program};
use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::Path;

/// One `p{i}` crate: its class modules (rewritten for cross-partition
/// seams) plus its slice of the registry (lookup/parents/meta) and the
/// link-table registration.
#[allow(clippy::too_many_arguments)] // the workspace seam surface; bundling would hide the data flow
pub(crate) fn emit_part(
    prog: &Program,
    out: &Path,
    lib_crate: &str,
    i: usize,
    part: &[&ClassPlan],
    method_ids: &HashMap<(String, String), u32>,
    opts: &Options,
    ws: &mut Ws,
    reuse: &BTreeMap<String, String>,
) -> crate::Result<()> {
    let member = format!("{lib_crate}-p{i}");
    let dir = out.join(format!("p{i}"));
    let classes_dir = dir.join("src").join("classes");
    std::fs::create_dir_all(&classes_dir)?;
    write_member_cargo(out, &format!("p{i}"), &member, lib_crate, false, false, ws)?;

    let own: HashSet<&str> = part.iter().map(|c| c.module.as_str()).collect();

    // class modules, rewritten ------------------------------------------------
    // Reuse path (M5 T06/T07): a verified-current class is kept
    // byte-for-byte and its rendering skipped. The rendered text depends
    // on the class's own bytecode plus this partition's seam inputs (own
    // set + method ids — both pinned by the global gate), so gate-passing
    // makes the skip sound.
    for c in part {
        if let Some(emitted_sha) = reuse.get(&c.name) {
            let emitted_path = classes_dir.join(format!("{}.rs", c.module));
            ws.entries.insert(
                c.name.clone(),
                Entry {
                    input_sha: c.input_sha.clone(),
                    emitted_sha: emitted_sha.clone(),
                    emitted_stat: crate::manifest::stat_of(&emitted_path),
                },
            );
            ws.stats.classes_reused += 1;
            continue;
        }
        let code = crate::emit::emit_class(prog, c, opts.emit_cfg, opts.emit_typed);
        let rewritten = rewrite_class_source(&code, &own, method_ids, &c.name)?;
        let dest = classes_dir.join(format!("{}.rs", c.module));
        ws.class_write(c, &dest, rewritten.as_bytes());
    }

    // classes/mod.rs -----------------------------------------------------------
    let mut classes_mod = String::from("// Generated by j2r — do not edit.\n");
    for c in part {
        let _ = writeln!(classes_mod, "pub mod {};", c.module);
    }
    ws.glue_write(&format!("p{i}/src/classes/mod.rs"), classes_mod.as_bytes())?;

    // lib.rs: registry slice + link registration (the four helpers below
    // carry the sections verbatim).
    let mut lib = format!("// Generated by j2r — do not edit.\n{ALLOW}\npub mod classes;\n\n");
    part_lookup_fn(&mut lib, opts, part);
    part_parents_fn(&mut lib, part);
    part_meta_tables(&mut lib, part);
    part_link_and_defaults(&mut lib, part, method_ids);
    ws.glue_write(&format!("p{i}/src/lib.rs"), lib.as_bytes())?;
    Ok(())
}

/// The partition lookup fn (verbatim from `emit_part`, round-5
/// reshaping). R7: the default is the pre-R7 string-tuple match (the
/// measured NO-GO — scripts/evidence/r7/); `opts.emit_hash_dispatch`
/// opts into the FNV-1a selector match via the SAME
/// dispatch_table::emit_lookup_fn the single-crate registry uses (one
/// source of truth). The <clinit> skip is preserved by BOTH shapes:
/// reached via statics::ensure.
pub(crate) fn part_lookup_fn(lib: &mut String, opts: &Options, part: &[&ClassPlan]) {
    if opts.emit_hash_dispatch {
        let lookup_entries: Vec<crate::dispatch_table::LookupEntry> = part
            .iter()
            .flat_map(|c| {
                c.methods
                    .iter()
                    .filter(|m| m.name != "<clinit>")
                    .map(move |m| crate::dispatch_table::LookupEntry {
                        class: c.name.clone(),
                        name: m.name.clone(),
                        desc: m.desc.clone(),
                        target: format!("crate::classes::{}::{}", c.module, m.fn_name),
                    })
            })
            .collect();
        crate::dispatch_table::emit_lookup_fn(lib, &lookup_entries);
        let _ = writeln!(lib);
    } else {
        let _ = writeln!(
            lib,
            "pub fn lookup(class: &str, name: &str, desc: &str) -> ::core::option::Option<::j2r_runtime::MethodFn> {{"
        );
        let _ = writeln!(lib, "    match (class, name, desc) {{");
        for c in part {
            for m in &c.methods {
                if m.name == "<clinit>" {
                    continue; // reached via statics::ensure, not dispatch
                }
                let _ = writeln!(
                    lib,
                    "        ({:?}, {:?}, {:?}) => ::core::option::Option::Some(crate::classes::{}::{} as ::j2r_runtime::MethodFn),",
                    c.name, m.name, m.desc, c.module, m.fn_name
                );
            }
        }
        let _ = writeln!(lib, "        _ => ::core::option::Option::None,");
        let _ = writeln!(lib, "    }}");
        let _ = writeln!(lib, "}}");
        let _ = writeln!(lib);
    }
}

/// The partition parents_of fn (verbatim from `emit_part`, round-5
/// reshaping).
pub(crate) fn part_parents_fn(lib: &mut String, part: &[&ClassPlan]) {
    let _ = writeln!(
        lib,
        "pub fn parents_of(class: &str) -> ::core::option::Option<&'static [&'static str]> {{"
    );
    let _ = writeln!(lib, "    match class {{");
    for c in part {
        let mut parents: Vec<&str> = Vec::new();
        parents.push(c.super_name.as_deref().unwrap_or("java/lang/Object"));
        for itf in &c.interfaces {
            parents.push(itf.as_str());
        }
        let list = parents
            .iter()
            .map(|p| format!("{p:?}"))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            lib,
            "        {:?} => ::core::option::Option::Some(&[{}]),",
            c.name, list
        );
    }
    let _ = writeln!(lib, "        _ => ::core::option::Option::None,");
    let _ = writeln!(lib, "    }}");
    let _ = writeln!(lib, "}}");
    let _ = writeln!(lib);
}

/// The reflection-subset meta tables + meta_of (verbatim from
/// `emit_part`, round-5 reshaping; same shape as the single-crate
/// registry).
pub(crate) fn part_meta_tables(lib: &mut String, part: &[&ClassPlan]) {
    for c in part {
        let tag = upper_snake(&c.module);
        let _ = writeln!(
            lib,
            "static FIELDS_{tag}: [::j2r_runtime::UserField; {}] = [",
            c.fields.len()
        );
        for f in &c.fields {
            // G4.2 arm (b): boundary fields are marked at every site the
            // generated crate exposes, including the reflection table.
            if let Some(marker) = crate::emit::jmm_boundary_marker(f, &c.name) {
                let _ = writeln!(lib, "    {marker}");
            }
            let _ = writeln!(
                lib,
                "    ::j2r_runtime::UserField {{ name: {:?}, desc: {:?}, is_static: {}, instance_slot: {}, static_slot: {}, modifiers: {} }},",
                f.name,
                f.desc,
                f.is_static,
                f.instance_slot.unwrap_or(0),
                f.static_slot.unwrap_or(0),
                f.modifiers
            );
        }
        let _ = writeln!(lib, "];");
        let declared_methods: Vec<_> = c
            .methods
            .iter()
            .filter(|m| m.name != "<init>" && m.name != "<clinit>")
            .collect();
        let _ = writeln!(
            lib,
            "static METHODS_{tag}: [::j2r_runtime::UserMethod; {}] = [",
            declared_methods.len()
        );
        for m in &declared_methods {
            let _ = writeln!(
                lib,
                "    ::j2r_runtime::UserMethod {{ name: {:?}, desc: {:?}, is_static: {}, is_native: {}, modifiers: {} }},",
                m.name, m.desc, m.is_static, m.is_native, m.modifiers
            );
        }
        let _ = writeln!(lib, "];");
        // R2 slice 3: declared constructors in CLASSFILE order (the
        // Temurin reversal is the runtime's law, not the metadata's).
        let ctors: Vec<_> = c.methods.iter().filter(|m| m.name == "<init>").collect();
        let _ = writeln!(
            lib,
            "static CTORS_{tag}: [::j2r_runtime::UserCtor; {}] = [",
            ctors.len()
        );
        for m in &ctors {
            let _ = writeln!(
                lib,
                "    ::j2r_runtime::UserCtor {{ desc: {:?}, modifiers: {} }},",
                m.desc, m.modifiers
            );
        }
        let _ = writeln!(lib, "];");
        let simple = match &c.simple_name {
            Some(s) => format!("::core::option::Option::Some({s:?})"),
            None => "::core::option::Option::None".to_string(),
        };
        // FORNAME-INIT: same metadata shape as the single-crate registry —
        // the class id and the clinit fn (the clinit lives in THIS
        // partition crate's classes module, so the direct path is legal
        // here; cross-partition ensure routes through the link table).
        let clinit_expr = match &c.clinit_fn {
            Some(fname) => format!(
                "::core::option::Option::Some(crate::classes::{}::{} as ::j2r_runtime::MethodFn)",
                c.module, fname
            ),
            None => "::core::option::Option::None".to_string(),
        };
        let _ = writeln!(
            lib,
            "static META_{tag}: ::j2r_runtime::UserClassInfo = ::j2r_runtime::UserClassInfo {{ id: {}, is_interface: {}, is_abstract: {}, simple_name: {}, nest_host: {:?}, total_slots: {}, defaults_spec: {:?}, fields: &FIELDS_{tag}, methods: &METHODS_{tag}, ctors: &CTORS_{tag}, clinit: {} }};",
            c.id, c.is_interface, c.is_abstract, simple, c.nest_host.clone(), c.total_slots, c.default_spec, clinit_expr
        );
    }
    let _ = writeln!(
        lib,
        "pub fn meta_of(class: &str) -> ::core::option::Option<&'static ::j2r_runtime::UserClassInfo> {{"
    );
    let _ = writeln!(lib, "    match class {{");
    for c in part {
        let tag = upper_snake(&c.module);
        let _ = writeln!(
            lib,
            "        {:?} => ::core::option::Option::Some(&META_{tag}),",
            c.name
        );
    }
    let _ = writeln!(lib, "        _ => ::core::option::Option::None,");
    let _ = writeln!(lib, "    }}");
    let _ = writeln!(lib, "}}");
    let _ = writeln!(lib);
}

/// register_link + the G2.1 defaults/constants register fns (verbatim
/// from `emit_part`, round-5 reshaping). G2.1 (console.md F3 /
/// REVIEW_CHECKLIST G2.1): the partition's defaults/constants tables
/// live HERE — bounded by k — and the app composes them at startup;
/// app/src/main.rs carries one line per partition, never a
/// total-class-scaled literal.
pub(crate) fn part_link_and_defaults(
    lib: &mut String,
    part: &[&ClassPlan],
    method_ids: &HashMap<(String, String), u32>,
) {
    let _ = writeln!(
        lib,
        "pub fn register_link(out: &mut Vec<::core::option::Option<::j2r_runtime::MethodFn>>) {{"
    );
    for c in part {
        for m in &c.methods {
            let gid = method_ids[&(c.module.clone(), m.fn_name.clone())];
            let _ = writeln!(
                lib,
                "    out[{}usize] = ::core::option::Option::Some(crate::classes::{}::{} as ::j2r_runtime::MethodFn);",
                gid, c.module, m.fn_name
            );
        }
    }
    let _ = writeln!(lib, "}}");
    let _ = writeln!(lib);
    lib.push_str(&crate::emit::static_defaults_register_fn(part));
    lib.push_str(&crate::emit::static_constants_register_fn(part));
}
