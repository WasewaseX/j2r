pub(crate) const ALLOW: &str = "#![allow(dead_code, unused_variables, unused_mut, unused_assignments, unused_labels, unreachable_code, unused_parens, unused_imports, non_snake_case)]\n";

/// Deterministic partition layout (verbatim from `emit_workspace`,
/// round-5 reshaping): name-sorted contiguous chunks of k, the class and
/// module -> part maps, and the global method-id table.
#[allow(clippy::type_complexity)] // the layout bundle rides the workspace seam
pub(crate) fn layout_parts(
    prog: &Program,
    k: usize,
) -> (
    Vec<Vec<&ClassPlan>>,
    HashMap<&str, usize>,
    HashMap<&str, usize>,
    HashMap<(String, String), u32>,
    u32,
) {
    let mut sorted: Vec<&ClassPlan> = prog.classes.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    let parts: Vec<Vec<&ClassPlan>> = sorted.chunks(k.max(1)).map(<[_]>::to_vec).collect();
    let part_of_module: HashMap<&str, usize> = parts
        .iter()
        .enumerate()
        .flat_map(|(i, p)| p.iter().map(move |c| (c.module.as_str(), i)))
        .collect();
    let part_of_name: HashMap<&str, usize> = parts
        .iter()
        .enumerate()
        .flat_map(|(i, p)| p.iter().map(move |c| (c.name.as_str(), i)))
        .collect();

    // Global method ids over the sorted classes, declaration order within
    // a class. Every method (including <init>/<clinit>) gets a slot: the
    // link table serves both direct cross-partition calls and the clinit
    // fn pointers passed to statics::ensure.
    let mut method_ids: HashMap<(String, String), u32> = HashMap::new();
    let mut total_methods = 0u32;
    for c in &sorted {
        for m in &c.methods {
            method_ids.insert((c.module.clone(), m.fn_name.clone()), total_methods);
            total_methods += 1;
        }
    }
    (
        parts,
        part_of_module,
        part_of_name,
        method_ids,
        total_methods,
    )
}

/// The per-class reuse scan (verbatim from `emit_workspace`'s gate block,
/// round-5 reshaping): a verified-current class keeps its recorded
/// emitted sha and skips rendering.
pub(crate) fn scan_reuse(
    prog: &Program,
    out: &Path,
    part_of_name: &HashMap<&str, usize>,
    m: &Manifest,
) -> BTreeMap<String, String> {
    let mut reuse: BTreeMap<String, String> = BTreeMap::new();
    for c in &prog.classes {
        let pi = part_of_name[&c.name.as_str()];
        let emitted_path = out
            .join(format!("p{pi}"))
            .join(crate::emit::class_file_rel(&c.module));
        if crate::manifest::verify_reuse(c, &emitted_path, m) {
            let entry = m.entries.get(&c.name).expect("verified entry exists");
            reuse.insert(c.name.clone(), entry.emitted_sha.clone());
        }
    }
    reuse
}

/// Workspace-level glue (verbatim from `emit_workspace`, round-5
/// reshaping): the workspace Cargo.toml, the vendored runtime, and the
/// support crate.
pub(crate) fn workspace_glue(
    out: &Path,
    lib_crate: &str,
    parts: &[Vec<&ClassPlan>],
    prior: Option<&Manifest>,
    ws: &mut Ws,
) -> crate::Result<()> {
    // workspace manifest ---------------------------------------------------
    let mut wsc = String::from("# Generated by j2r — partitioned workspace (M5 T05).\n");
    let _ = writeln!(wsc, "[workspace]");
    let _ = writeln!(wsc, "members = [\"support\", \"app\",");
    for i in 0..parts.len() {
        let _ = writeln!(wsc, "  \"p{i}\",");
    }
    let _ = writeln!(wsc, "]");
    let _ = writeln!(wsc, "resolver = \"2\"");
    ws.glue_write("Cargo.toml", wsc.as_bytes())?;

    // vendored runtime, once, shared by every member ------------------------
    let _sp_glue = crate::StageGuard::enter("emit_runtime_glue");
    crate::emit::copy_runtime(out)?;
    crate::emit::record_runtime_glue_pub(out, &mut ws.glue, prior, ws.stats);
    drop(_sp_glue);

    emit_support(out, lib_crate, ws)
}

/// The manifest save + stats hand-off (verbatim from `emit_workspace`,
/// round-5 reshaping).
#[allow(clippy::type_complexity)]
pub(crate) fn finish_manifest(
    opts: &Options,
    out: &Path,
    surface: String,
    layout: String,
    entries: BTreeMap<String, Entry>,
    glue: BTreeMap<String, String>,
    stats: &mut EmitStats,
) -> crate::Result<EmitStats> {
    let manifest = Manifest {
        emitter: EMITTER_VERSION,
        emit_cfg: opts.emit_cfg,
        emit_typed: opts.emit_typed,
        surface,
        layout,
        crate_name: opts
            .crate_name
            .chars()
            .map(|c| if c == '\t' || c == '\n' { '_' } else { c })
            .collect(),
        entries,
        glue,
    };
    manifest.save(out)?;
    let mut stats = std::mem::take(stats);
    stats.manifest_path = Manifest::path(out);
    Ok(stats)
}
