//! `partition`::member — the verbatim
//! items of the round-7 file-split pass (the parent glob
//! re-exports preserve every pre-split path).
use super::*;
use crate::manifest::{write_if_changed, EmitStats, Entry};
use crate::sha256::sha256_hex;
use crate::ClassPlan;
use std::collections::BTreeMap;
use std::path::Path;

/// Workspace write context: routes every crate-level file through
/// write-if-changed, records its manifest hash, and accumulates the
/// per-class entries emit_part fills in.
pub(crate) struct Ws<'a> {
    pub(crate) out: &'a Path,
    pub(crate) glue: BTreeMap<String, String>,
    pub(crate) entries: BTreeMap<String, Entry>,
    pub(crate) stats: &'a mut EmitStats,
}

impl Ws<'_> {
    pub(crate) fn glue_write(&mut self, rel: &str, bytes: &[u8]) -> crate::Result<()> {
        if write_if_changed(&self.out.join(rel), bytes)? {
            self.stats.files_written += 1;
        } else {
            self.stats.files_unchanged += 1;
        }
        self.glue.insert(rel.to_string(), sha256_hex(bytes));
        Ok(())
    }

    pub(crate) fn class_write(&mut self, class: &ClassPlan, rel_path: &Path, bytes: &[u8]) {
        if write_if_changed(rel_path, bytes).unwrap_or(false) {
            self.stats.files_written += 1;
        } else {
            self.stats.files_unchanged += 1;
        }
        self.entries.insert(
            class.name.clone(),
            Entry {
                input_sha: class.input_sha.clone(),
                emitted_sha: sha256_hex(bytes),
                emitted_stat: crate::manifest::stat_of(rel_path),
            },
        );
        self.stats.classes_reemitted += 1;
    }
}

pub(crate) fn part_dep(i: usize, lib_crate: &str) -> String {
    format!("{lib_crate}-p{i}")
}

pub(crate) fn write_member_cargo(
    out: &Path,
    dir_name: &str,
    package: &str,
    lib_crate: &str,
    is_app: bool,
    has_bin: bool,
    ws: &mut Ws,
) -> crate::Result<()> {
    let dir = out.join(dir_name);
    std::fs::create_dir_all(dir.join("src"))?;
    let mut cargo = String::new();
    if is_app {
        let _ = writeln!(cargo, "[package]");
        let _ = writeln!(cargo, "name = \"{package}\"");
        let _ = writeln!(cargo, "version = \"0.1.0\"");
        let _ = writeln!(cargo, "edition = \"2021\"");
        let _ = writeln!(cargo);
        let _ = writeln!(cargo, "[lib]");
        let _ = writeln!(cargo, "name = \"{lib_crate}\"");
        let _ = writeln!(cargo, "path = \"src/lib.rs\"");
        let _ = writeln!(cargo);
        if has_bin {
            let bin = crate::emit::bin_name_pub(&package.replace('-', "_"));
            let _ = writeln!(cargo, "[[bin]]");
            let _ = writeln!(cargo, "name = \"{bin}\"");
            let _ = writeln!(cargo, "path = \"src/main.rs\"");
            let _ = writeln!(cargo);
        }
    } else {
        let _ = writeln!(cargo, "[package]");
        let _ = writeln!(cargo, "name = \"{package}\"");
        let _ = writeln!(cargo, "version = \"0.1.0\"");
        let _ = writeln!(cargo, "edition = \"2021\"");
        let _ = writeln!(cargo);
    }
    let _ = writeln!(cargo, "[dependencies]");
    let _ = writeln!(cargo, "j2r-runtime = {{ path = \"../runtime\" }}");
    let _ = writeln!(
        cargo,
        "support = {{ package = \"{lib_crate}-support\", path = \"../support\" }}"
    );
    ws.glue_write(&format!("{dir_name}/Cargo.toml"), cargo.as_bytes())?;
    Ok(())
}

/// The registry hook module the support crate carries: the app installs
/// the composite `parents_of` / `meta_of` fn pointers at startup; the
/// partition class modules call through the hook. A miss panics loudly —
/// never a wrong subtype answer.
pub(crate) fn registry_hook_source() -> String {
    r#"// Generated by j2r — do not edit.
//! The registry hook (external-B2, jbox2d port report): the exception-
//! matcher helper in every class module references `parents_of` /
//! `meta_of`; in partitioned emission those composite tables live in the
//! app crate, which the partitions cannot depend on (app depends on
//! p0..pN — a cargo cycle). The app installs the fn pointers here at
//! startup, the same process-global-slot pattern as the link table and
//! the dispatch slot. A use-before-install panics loudly ("registry hook
//! not installed before use") — never a wrong subtype answer.

pub(crate) static PARENTS: ::std::sync::OnceLock<
    fn(&str) -> ::core::option::Option<&'static [&'static str]>,
> = ::std::sync::OnceLock::new();
pub(crate) static META: ::std::sync::OnceLock<
    fn(&str) -> ::core::option::Option<&'static ::j2r_runtime::UserClassInfo>,
> = ::std::sync::OnceLock::new();

/// Installs the composite registry fn pointers (idempotent-safe: a
/// double install is an emitter bug and fails loud).
pub fn install(
    parents: fn(&str) -> ::core::option::Option<&'static [&'static str]>,
    meta: fn(&str) -> ::core::option::Option<&'static ::j2r_runtime::UserClassInfo>,
) {
    let _ = PARENTS.set(parents);
    if META.set(meta).is_err() {
        panic!("j2r internal: registry hook installed twice");
    }
}

pub fn parents_of(class: &str) -> ::core::option::Option<&'static [&'static str]> {
    let f = *PARENTS
        .get()
        .expect("j2r internal: registry hook not installed before use (parents)");
    f(class)
}

pub fn meta_of(
    class: &str,
) -> ::core::option::Option<&'static ::j2r_runtime::UserClassInfo> {
    let f = *META
        .get()
        .expect("j2r internal: registry hook not installed before use (meta)");
    f(class)
}
"#
    .to_string()
}
