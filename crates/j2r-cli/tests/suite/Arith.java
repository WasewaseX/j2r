public class Arith {
    public static void main(String[] args) {
        int a = 17, b = 5;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println(-a);
        System.out.println(Integer.MAX_VALUE + 1);
        System.out.println(Integer.MIN_VALUE - 1);
        System.out.println(Integer.MIN_VALUE / -1);
        System.out.println(0x7fffffff << 3);
        System.out.println(-16 >> 2);
        System.out.println(-16 >>> 28);
        System.out.println(0b1010 & 0x0c);
        System.out.println(0b1010 | 0x0c);
        System.out.println(0b1010 ^ 0x0c);
        System.out.println(~0);
        int c = 3;
        c += 4; c -= 1; c *= 2; c /= 3; c %= 3;
        System.out.println(c);
        c <<= 4; c >>= 1; c |= 2; c &= 14; c ^= 5;
        System.out.println(c);
        long x = 9000000000L;
        System.out.println(x * 3);
        System.out.println(x % 7);
        System.out.println(x / 1000000000L);
        System.out.println(Long.MIN_VALUE / -1);
        System.out.println(x << 2);
        System.out.println(-x >>> 40);
        System.out.println(x & 0xffL);
        System.out.println(x | 1L);
        System.out.println(x ^ 0xffffffffL);
        System.out.println((int) x);
        System.out.println((long) 2147483647 + 1);
        byte bt = (byte) 200;
        System.out.println(bt);
        short sh = (short) 70000;
        System.out.println(sh);
        char ch = (char) 65601;
        System.out.println((int) ch);
        double d = 7.5;
        System.out.println(d / 2.5);
        System.out.println(d % 2.0);
        System.out.println(d * 2);
        float f = 1.5f;
        System.out.println(f * 4.0f);
        System.out.println((int) d);
        System.out.println((long) d);
        System.out.println((int) -3.99);
        System.out.println((byte) 130.5);
        System.out.println(1.0 / 0.0);
        System.out.println(-1.0 / 0.0);
        System.out.println(0.0 / 0.0);
        System.out.println(1.0e300 * 1.0e300);
        System.out.println(0.1 + 0.2);
        System.out.println(1.0 / 3.0);
        System.out.println(2.0e-5);
    }
}
